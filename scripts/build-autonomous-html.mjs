html=html.replace('<meta name="description" content="Cartographie, étude de faisabilité et veille des aides & financements publics.">','<meta name="description" content="LEYTON RADAR v12.2.0 — bibliothèque autonome avec actualisation live, faisabilité et veille.">');
const out=path.join(ROOT,'LEYTON-RADAR-v12.2.0-AUTONOME-LIVE.html');
