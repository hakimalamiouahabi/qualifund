await purgeIndirectSources();
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const SITE=path.join(ROOT,'site');
const read=f=>fs.readFile(path.join(SITE,f),'utf8');
let html=await read('index.html');
const css=await read('styles.css');
const runtime=await read('runtime-config.js');
const scoring=await read('scoring-core.js');
const app=await read('app.js');
const library=JSON.parse(await read('data/library.json'));
const sources=JSON.parse(await read('data/sources.json'));
const coverage=JSON.parse(await read('data/coverage.json'));
const changes=JSON.parse(await read('data/changes.json'));
const readiness=JSON.parse(await read('data/production-readiness.json'));
const bootstrap=`window.__LEYTON_RADAR_BOOTSTRAP__=${JSON.stringify({library,sources,coverage,changes})};\nwindow.__QUALIFUND_BOOTSTRAP__=window.__LEYTON_RADAR_BOOTSTRAP__;\nwindow.__LEYTON_RADAR_READINESS__=${JSON.stringify(readiness)};`;
html=html.replace('<link rel="manifest" href="manifest.webmanifest"><link rel="stylesheet" href="styles.css">',`<style>${css}</style>`);
html=html.replace('<script src="./runtime-config.js"></script><script src="./data/bootstrap.js"></script><script src="scoring-core.js"></script><script src="app.js"></script><script>if(\'serviceWorker\'in navigator){navigator.serviceWorker.register(\'./sw.js\').catch(()=>{})}</script>',`<script>${runtime}</script><script>${bootstrap}</script><script>${scoring}</script><script>${app}</script>`);
html=html.replace('id="engineBadge">Cartographie · Faisabilité · Veille','id="engineBadge">HTML autonome · Live à l’ouverture · Faisabilité · Veille');
